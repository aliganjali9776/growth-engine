export function recommendedFocus(
  dimension: AssessmentDimension,
  findings: DiagnosticIssue[],
) {
  const weakest = findings[0];
  if (findings.every((f) => f.severity === "strength"))
    return {
      focus: `حفظ و انتقال نقاط قوت ${dimension === "system" ? "سیستم" : dimension === "strategy" ? "استراتژی" : "اسکیل"}`,
      action:
        "یک اجرای واقعی بدون حضور فرد کلیدی را بررسی کنید، دانش موجود را به تیم منتقل کنید و پایداری کیفیت را در حجم کاری بیشتر بسنجید.",
    };
  if (weakest.answer === 4)
    return {
      focus: weakest.title,
      action:
        "برای این قابلیت یک معیار اجرای یکسان و مالک مشخص تعیین کنید؛ آن را توسط فرد دیگری اجرا و نتیجه را در یک مرور دوره‌ای بررسی کنید.",
    };
  return (
    specific[weakest.id] ?? {
      focus: `تقویت ${questions.find((q) => q.id === weakest.id)!.focus}`,
      action: `در حوزه «${questions.find((q) => q.id === weakest.id)!.focus}» یک نمونه واقعی از شکاف را ثبت کنید؛ سپس مالک اصلاح، معیار نتیجه و موعد بازبینی را با تیم مشخص کنید.`,
    }
  );
}
